let platform: 'android' | null = null;
const merged = new Map<string, Strings>();
/** Which app we run in, for `stringsFor`. Set once, before the first render. */
export function setPlatform(p: 'android' | null): void {
  platform = p;
  merged.clear();
}

/** A language's strings as this platform words them. Components get them as `t`. A language not loaded yet falls back to English. */
export function stringsFor(lang: Language): Strings {
  if (!translations[lang]) lang = 'en';
  if (platform !== 'android') return translations[lang];
  let all = merged.get(lang);
  if (!all) { all = { ...translations[lang], ...androidStrings[lang] }; merged.set(lang, all); }
  return all;
}

/**
 * Makes a language ready: Arabic comes from its own chunk (translations.ar.ts),
 * so German and English users never download it. Call before switching to a
 * language and before the first render; resolves at once when it is there.
 */
export async function loadLanguage(lang: Language): Promise<void> {
  if (translations[lang]) return;
  if (lang === 'ar') {
    const m = await import('./translations.ar');
    translations.ar = m.ar;
    androidStrings.ar = m.arAndroid;
    EXTRA_PLURALS[m.ar.locale] = m.arPlurals;
    ANDROID_EXTRA_PLURALS[m.ar.locale] = m.arAndroidPlurals;
    merged.delete('ar');
  }
}

let firstRun: Promise<void> | null = null;
/**
 * Makes the first run's German and English strings ready (translations.firstRun.ts: the welcome,
 * the photo access, the first scan, the reveal, the guided review, the safety moments, the tips, So
 * funktioniert Bildklar). They are a chunk of their own, so a start that shows none of it never
 * loads them: App.tsx loads them together with each screen that needs them. Laid into the objects
 * the app already holds, so a `t` handed out earlier has them too.
 */
export function loadFirstRun(): Promise<void> {
  firstRun ??= import('./translations.firstRun').then(m => {
    Object.assign(translations.de, m.deFirstRun);
    Object.assign(translations.en, m.enFirstRun);
    Object.assign(androidStrings.de, m.deFirstRunAndroid);
    Object.assign(androidStrings.en, m.enFirstRunAndroid);
    const de = merged.get('de');
    if (de) Object.assign(de, m.deFirstRun, m.deFirstRunAndroid);
    const en = merged.get('en');
    if (en) Object.assign(en, m.enFirstRun, m.enFirstRunAndroid);
  });
  return firstRun;
}

